#include <stdio.h>
int main() {
    printf("Olá mundo!\n");
    printf("Valor inteiro: %d.\n", 10);
    printf("Valor real: %f.\n", 3.14156744); //%f é usado para indicar números com vírgula
    printf("Valor real com formatação de duas casas: %.2f\n", 3.123123412);
    printf("Texto: %c\n", 'a');
    printf("Dado de texto: %s.\n", "testando");
}